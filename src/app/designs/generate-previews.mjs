// Run from the repository root: node src/app/designs/generate-previews.mjs
// Originals and their watermarks are never edited. These are static-export assets.
import { mkdir, readFile, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const originals = path.join(root, "public/images/designs");
const output = path.join(originals, "lookbook");
await mkdir(output, { recursive: true });
const previews = {};
let originalBytes = 0;
let previewBytes = 0;

for (let number = 1; number <= 20; number++) {
  const name = `design-${String(number).padStart(2, "0")}`;
  const original = await readFile(path.join(originals, `${name}.jpeg`));
  originalBytes += original.length;
  const variants = [];
  for (const width of [640, 1200]) {
    const { data, info } = await sharp(original)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: width === 640 ? 68 : 74, effort: 5 })
      .toBuffer({ resolveWithObject: true });
    if (variants.some((variant) => variant.width === info.width)) continue;
    const filename = `${name}-${info.width}.webp`;
    await writeFile(path.join(output, filename), data);
    previewBytes += (await stat(path.join(output, filename))).size;
    variants.push({ src: `/images/designs/lookbook/${filename}`, width: info.width });
  }
  previews[number] = variants;
}

await writeFile(
  new URL("./lookbook-previews.ts", import.meta.url),
  `// Generated by generate-previews.mjs. Do not edit original photographs.\nexport const lookbookPreviews: Record<number, readonly { src: \`/images/\${string}\`; width: number }[]> = ${JSON.stringify(previews, null, 2)};\n`,
);
console.log(JSON.stringify({ originalBytes, previewBytes, photographs: 20 }));
